/**
 * Writes `src/icons.ts`: the Phosphor Regular icons the app uses, as path
 * data scaled from Phosphor's 256 grid to the 24 one Groundwork's `icon`
 * attribute draws on. Add a name here and run `bun run icons` to use another
 * icon.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import svgpath from "svgpath";

const names = [
  "arrow-counter-clockwise",
  "arrow-down",
  "arrow-left",
  "arrow-up",
  "cards",
  "copy",
  "dots-three-vertical",
  "download-simple",
  "envelope-simple",
  "gear",
  "hand-tap",
  "image",
  "link-simple",
  "magnifying-glass",
  "music-notes",
  "palette",
  "pencil-simple",
  "plus",
  "shuffle",
  "sparkle",
  "speaker-high",
  "speaker-slash",
  "storefront",
  "trash",
  "x",
];

const exportName = (name: string) =>
  `ph${name.replace(/(?:^|-)(\w)/g, (_, letter: string) => letter.toUpperCase())}`;

const pathData = (name: string) => {
  const file = fileURLToPath(
    import.meta.resolve(`@phosphor-icons/core/assets/regular/${name}.svg`),
  );

  const paths = [...readFileSync(file, "utf8").matchAll(/<path d="([^"]+)"/g)];

  if (paths.length !== 1 || paths[0]?.[1] === undefined) {
    throw new Error(`${name} isn't one path, so it needs a slotted <svg>`);
  }

  return svgpath(paths[0][1])
    .scale(24 / 256)
    .round(2)
    .toString();
};

const icons = names
  .toSorted((a, b) => a.localeCompare(b))
  .map((name) => `export const ${exportName(name)} = "${pathData(name)}";`);

writeFileSync(
  fileURLToPath(new URL("../src/icons.ts", import.meta.url)),
  `// Generated by \`bun run icons\` from Phosphor's icons. Don't edit.\n\n${icons.join("\n\n")}\n`,
);
